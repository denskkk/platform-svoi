-- Китай: структура замовника змінилася на 10 папок. Перенесення оголошень зі старих розділів у нові (повторний запуск безпечний).
UPDATE listings SET data = data || jsonb_build_object('section', CASE data->>'section'
    WHEN 'china_sourcing_factory' THEN 'china_search_manufacturer'
    WHEN 'china_sourcing_product' THEN 'china_search_product'
    WHEN 'china_sourcing_other' THEN 'china_search_custom'
    WHEN 'china_brand_develop' THEN 'china_brand_create'
    WHEN 'china_brand_manufacturer' THEN 'china_brand_production'
    WHEN 'china_brand_other' THEN 'china_brand_custom'
    WHEN 'china_recalc_products' THEN 'china_consult_turnkeyCalc'
    WHEN 'china_recalc_analog' THEN 'china_search_analogs'
    WHEN 'china_recalc_rate' THEN 'china_finance_rate'
    WHEN 'china_recalc_other' THEN 'china_consult_working'
    WHEN 'china_yuan_buy' THEN 'china_finance_exchange'
    WHEN 'china_yuan_pay' THEN 'china_finance_payment'
    WHEN 'china_yuan_other' THEN 'china_finance_support'
    WHEN 'china_otherRequest' THEN 'china_consult_custom'
    WHEN 'china_logistics_air' THEN 'china_logistics_air'
    WHEN 'china_logistics_rail' THEN 'china_logistics_rail'
    WHEN 'china_logistics_sea' THEN 'china_logistics_sea'
    WHEN 'china_logistics_road' THEN 'china_logistics_road'
    WHEN 'china_logistics_multimodal' THEN 'china_logistics_groupage'
  END)
WHERE project_slug = 'china'
  AND data->>'section' IN ('china_sourcing_factory','china_sourcing_product','china_sourcing_other','china_brand_develop','china_brand_manufacturer','china_brand_other','china_recalc_products','china_recalc_analog','china_recalc_rate','china_recalc_other','china_yuan_buy','china_yuan_pay','china_yuan_other','china_otherRequest','china_logistics_multimodal');
